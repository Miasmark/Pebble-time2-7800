#!/usr/bin/env python3
"""Build the clock stub: an 8K 7800 cartridge that draws the time from the clock registers.

    python tools/mkstub.py --toolkit ../a7800-toolkit -o build/clockstub.a78

The smallest thing that proves the watch path end to end: real MARIA display
lists, 160A graphics in ROM laid out line-planar for 16-line zones, a display
list list in ROM, and the time read from $4000 every frame (docs/clock-registers.md).
When the minute changes, the digits flash; a ship crosses the bottom of the
screen. It is assembled with the a7800 toolkit's tools/asm.py and given a header
by its newgame.header().

8K is half the smallest commercial cartridge (16K). No signature: the watch
starts it without a BIOS, as the a7800 fork of MAME does in its no-BIOS mode.
"""
import argparse
import os
import sys

ROM_BASE = 0xE000
GFX = 0xE000           # 16 pages: page $E0 + (15 - line) holds line `line` of every glyph
CODE = 0xF000         # the display list list, then the code
GLYPH_BYTES = 4        # 16 pixels at 160A
DLL_ZONES = 16         # 16 x 16 lines covers every DMA line (17-258)
DLBASE = 0x1900        # 32 bytes per zone's display list
DL_STRIDE = 32
TIME_ZONE = 5
SHIP_ZONE = 11
TIME_X = [32, 52, 72, 92, 112]

BIG_DIGITS = [
    [0x1F, 0x11, 0x11, 0x11, 0x11, 0x11, 0x1F],
    [0x0C, 0x04, 0x04, 0x04, 0x04, 0x04, 0x1F],
    [0x1F, 0x01, 0x01, 0x1F, 0x10, 0x10, 0x1F],
    [0x1F, 0x01, 0x01, 0x0F, 0x01, 0x01, 0x1F],
    [0x11, 0x11, 0x11, 0x1F, 0x01, 0x01, 0x01],
    [0x1F, 0x10, 0x10, 0x1F, 0x01, 0x01, 0x1F],
    [0x1F, 0x10, 0x10, 0x1F, 0x11, 0x11, 0x1F],
    [0x1F, 0x01, 0x01, 0x02, 0x04, 0x04, 0x04],
    [0x1F, 0x11, 0x11, 0x1F, 0x11, 0x11, 0x1F],
    [0x1F, 0x11, 0x11, 0x1F, 0x01, 0x01, 0x1F],
]
COLON = [0x00, 0x04, 0x04, 0x00, 0x04, 0x04, 0x00]

SHIP = [   # 16 x 9, colours 1-3 of palette 1
    ".......33.......",
    "......3113......",
    "......1221......",
    ".....122221.....",
    "....12222221....",
    "...1221111221...",
    "..122122221221..",
    ".11.1.1111.1.11.",
    ".3...3....3...3.",
]


def glyph_lines(rows):
    """A 5x7 font glyph as 16 lines of 16 pixels (colour per pixel, 0 = transparent).
    Each font pixel is 3 wide and 2 tall; rows 0-1 colour 3, 2-4 colour 2, 5-6 colour 1."""
    lines = [[0] * 16 for _ in range(16)]
    for r, bits in enumerate(rows):
        colour = 3 if r < 2 else (2 if r < 5 else 1)
        for c in range(5):
            if bits & (0x10 >> c):
                for dy in range(2):
                    for dx in range(3):
                        lines[1 + 2 * r + dy][c * 3 + dx] = colour
    return lines


def ship_lines():
    lines = [[0] * 16 for _ in range(16)]
    for r, row in enumerate(SHIP):
        for c, ch in enumerate(row):
            lines[4 + r][c] = 0 if ch == "." else int(ch)
    return lines


def pack160a(pixels):
    out = []
    for b in range(0, 16, 4):
        v = 0
        for p in range(4):
            v |= (pixels[b + p] & 3) << (6 - 2 * p)
        out.append(v)
    return out


def source():
    glyphs = [glyph_lines(d) for d in BIG_DIGITS] + [glyph_lines(COLON), ship_lines()]
    L = []
    a = L.append
    a("; clockstub -- generated by a7800-pebble-tools/tools/mkstub.py")
    a("INPTCTRL = $01")
    a("VBLANK   = $01")
    a("BACKGRND = $20")
    a("P0C1     = $21")
    a("P0C2     = $22")
    a("P0C3     = $23")
    a("P1C1     = $25")
    a("P1C2     = $26")
    a("P1C3     = $27")
    a("MSTAT    = $28")
    a("DPPH     = $2C")
    a("DPPL     = $30")
    a("OFFSET   = $38")
    a("CTRL     = $3C")
    a("CLK_MIN  = $4001")
    a("CLK_HOUR = $4002")
    a("FRAME    = $0080")
    a("LASTMIN  = $0081")
    a("FLASH    = $0082")
    a("HPOS     = $0083")
    a("DLBASE   = $%04X" % DLBASE)
    a("TIME_DL  = $%04X" % (DLBASE + TIME_ZONE * DL_STRIDE))
    a("SHIP_DL  = $%04X" % (DLBASE + SHIP_ZONE * DL_STRIDE))
    a("")
    a("    .org $%04X" % ROM_BASE)
    a("gfx:")
    for page in range(16):
        line = 15 - page          # MARIA reads page (high + offset); offset counts 15..0
        data = []
        for g in glyphs:
            data += pack160a(g[line])
        a("    .byte " + ",".join("$%02X" % b for b in data))
        a("    .res $%X,$00" % (256 - len(data)))
    a("")
    a("dll:")
    for z in range(DLL_ZONES):
        dl = DLBASE + z * DL_STRIDE
        a("    .byte $0F,$%02X,$%02X" % (dl >> 8, dl & 0xFF))
    a("xpos:")
    a("    .byte " + ",".join("$%02X" % x for x in TIME_X))
    a("")
    a("reset:")
    a("    SEI")
    a("    CLD")
    a("    LDX #$FF")
    a("    TXS")
    a("    LDA #$17")
    a("    STA INPTCTRL")
    a("    LDA #$00")
    a("    STA OFFSET")
    a("    STA VBLANK")
    a("    LDA #$60                  ; DMA off while the lists are built")
    a("    STA CTRL")
    a("    LDA #$00")
    a("    STA BACKGRND")
    a("    LDA #$36")
    a("    STA P0C1                  ; red")
    a("    LDA #$28")
    a("    STA P0C2                  ; orange")
    a("    LDA #$1E")
    a("    STA P0C3                  ; yellow")
    a("    LDA #$0E")
    a("    STA P1C1                  ; white")
    a("    LDA #$08")
    a("    STA P1C2                  ; grey")
    a("    LDA #$9E")
    a("    STA P1C3                  ; light blue")
    a("    LDA #$00")
    a("    TAX")
    a("clear:")
    a("    STA DLBASE,X")
    a("    STA DLBASE+$100,X")
    a("    INX")
    a("    BNE clear")
    a("    STA FRAME")
    a("    STA FLASH")
    a("    LDA CLK_MIN")
    a("    STA LASTMIN")
    a("    LDA #>dll")
    a("    STA DPPH")
    a("    LDA #<dll")
    a("    STA DPPL")
    a("    LDA #$40                  ; DMA on, 160A")
    a("    STA CTRL")
    a("")
    a("main:")
    a("wait_vb:")
    a("    LDA MSTAT")
    a("    BPL wait_vb               ; wait for vertical blank")
    a("")
    a("    ; the time, from the clock registers, as five 4-byte entries")
    a("    LDA CLK_HOUR")
    a("    LSR")
    a("    LSR")
    a("    LSR")
    a("    LSR")
    a("    LDY #$00")
    a("    JSR put_glyph")
    a("    LDA CLK_HOUR")
    a("    AND #$0F")
    a("    LDY #$04")
    a("    JSR put_glyph")
    a("    LDA #$0A                  ; colon")
    a("    LDY #$08")
    a("    JSR put_glyph")
    a("    LDA CLK_MIN")
    a("    LSR")
    a("    LSR")
    a("    LSR")
    a("    LSR")
    a("    LDY #$0C")
    a("    JSR put_glyph")
    a("    LDA CLK_MIN")
    a("    AND #$0F")
    a("    LDY #$10")
    a("    JSR put_glyph")
    a("")
    a("    ; a new minute: flash the digits for a second")
    a("    LDA CLK_MIN")
    a("    CMP LASTMIN")
    a("    BEQ no_new_minute")
    a("    STA LASTMIN")
    a("    LDA #$3C")
    a("    STA FLASH")
    a("no_new_minute:")
    a("    LDA FLASH")
    a("    BEQ steady")
    a("    DEC FLASH")
    a("    LDA FRAME")
    a("    AND #$04")
    a("    BEQ steady")
    a("    LDA #$0E")
    a("    STA P0C3")
    a("    STA P0C2")
    a("    JMP colours_done")
    a("steady:")
    a("    LDA #$1E")
    a("    STA P0C3")
    a("    LDA #$28")
    a("    STA P0C2")
    a("colours_done:")
    a("")
    a("    ; the ship crosses the bottom of the screen")
    a("    LDA #$2C                  ; glyph 11")
    a("    STA SHIP_DL")
    a("    LDA #$3C                  ; palette 1, width 4")
    a("    STA SHIP_DL+1")
    a("    LDA #>gfx")
    a("    STA SHIP_DL+2")
    a("    LDA FRAME")
    a("    STA SHIP_DL+3")
    a("    INC FRAME")
    a("")
    a("wait_novb:")
    a("    LDA MSTAT")
    a("    BMI wait_novb")
    a("    JMP main")
    a("")
    a("; A = glyph number, Y = offset of the entry in TIME_DL")
    a("put_glyph:")
    a("    ASL")
    a("    ASL")
    a("    STA TIME_DL,Y")
    a("    LDA #$1C                  ; palette 0, width 4")
    a("    STA TIME_DL+1,Y")
    a("    LDA #>gfx")
    a("    STA TIME_DL+2,Y")
    a("    TYA")
    a("    LSR")
    a("    LSR")
    a("    TAX")
    a("    LDA xpos,X")
    a("    STA TIME_DL+3,Y")
    a("    RTS")
    a("")
    a("nmi:")
    a("    RTI")
    a("code_end:")
    a("    .res $FFFA-code_end,$00")
    a("    .word nmi")
    a("    .word reset")
    a("    .word nmi")
    return "\n".join(L) + "\n"


def main():
    ap = argparse.ArgumentParser(description=__doc__.strip().split("\n")[0])
    ap.add_argument("--toolkit", required=True, help="path to the a7800-toolkit checkout")
    ap.add_argument("-o", "--output", required=True)
    args = ap.parse_args()
    sys.path.insert(0, os.path.join(args.toolkit, "tools"))
    import asm
    import newgame

    src = source()
    with open(os.path.splitext(args.output)[0] + ".asm", "w") as f:
        f.write(src)
    data = asm.Assembler().assemble(src.splitlines())
    if len(data) != 0x10000 - ROM_BASE:
        raise SystemExit("assembled %d bytes, expected %d" % (len(data), 0x10000 - ROM_BASE))
    with open(args.output, "wb") as f:
        f.write(newgame.header(len(data), "PEBBLE CLOCK STUB"))
        f.write(data)
    print("wrote %s (%d bytes + 128-byte header)" % (args.output, len(data)))


if __name__ == "__main__":
    main()
