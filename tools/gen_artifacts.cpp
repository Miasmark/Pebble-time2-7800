// Builds the watch's artifact-colour table (watchface/src/c/emu/artifact_table.h)
// from the a7800 fork's composite video model.
//
//   c++ -O2 -std=c++17 -I<fork>/src/mame/atari tools/gen_artifacts.cpp -o build/gen_artifacts
//   build/gen_artifacts > watchface/src/c/emu/artifact_table.h
//
// In the 320 modes a pair of MARIA pixels is one colour cycle, and the watch
// shows each pair as one pixel. The fork's a7800_composite.h (a clock-for-clock
// port of MiSTer's composite encoder and decoder, with its settings) is run
// over every pair of codes (a, b) repeated across a line; the colour the TV
// decodes is, to within rounding, F(a) + G(b) -- the decoder is linear but for
// clipping at black and white, so the fit ignores clipped samples. A solid
// colour is F(a) + G(a), so a pattern's colour is the mean of its two solid
// colours plus D(a) - D(b), with D = (F - G) / 2: the artifact. The watch
// adds that to the mean of its own palette's two colours, so solid colours
// stay exactly what they are in the 160 modes.
//
// Settings: the fork's defaults with Composite Video on -- smear 1, AGC on,
// comb off, artifact phase 1 (a console's), the warm delay line, and the
// colour pin offset fitted to a console (0.08 V).

#include "a7800_composite.h"

#include <cmath>
#include <cstdio>
#include <vector>

int main() {
  static a7800_composite comp;
  a7800_composite::settings st;
  st.smear = 1;
  st.agc = true;
  st.comb = false;
  st.phase_adj = 1;
  st.temp = 0;
  st.colour_offset = 167772;   // 0.08 V, Q2.21
  comp.set(st);

  // the TV's colour of each pair at 320 pixels 160-161 (the watch's column 80)
  std::vector<double> obs(256 * 256 * 3);
  uint8_t codes[a7800_composite::LINE_CLOCKS];
  uint32_t rgb[a7800_composite::SAMPLES];
  for (int a = 0; a < 256; a++) {
    for (int b = 0; b < 256; b++) {
      std::fill(codes, codes + a7800_composite::LINE_CLOCKS, 0);
      for (int x = 0; x < 320; x += 2) {
        codes[a7800_composite::PICTURE_START + x] = (uint8_t)a;
        codes[a7800_composite::PICTURE_START + x + 1] = (uint8_t)b;
      }
      for (int k = 0; k < 3; k++) comp.line(codes, false, false, rgb);   // let the AGC settle
      double sum[3] = {0, 0, 0};
      for (int x = 160; x < 162; x++) {
        for (int j = 0; j < 2; j++) {
          uint32_t v = rgb[2 * (a7800_composite::PICTURE_START + x) + a7800_composite::LATENCY + j];
          sum[0] += v >> 16 & 255;
          sum[1] += v >> 8 & 255;
          sum[2] += v & 255;
        }
      }
      for (int c = 0; c < 3; c++) obs[(a * 256 + b) * 3 + c] = sum[c] / 4;
    }
  }

  // fit obs(a, b) = F(a) + G(b), where a clipped sample only says "at or beyond"
  std::vector<double> F(256 * 3), G(256 * 3), tgt(obs.size());
  for (int a = 0; a < 256; a++) {
    for (int c = 0; c < 3; c++) {
      F[a * 3 + c] = obs[(a * 256 + a) * 3 + c] / 2;
      G[a * 3 + c] = F[a * 3 + c];
    }
  }
  for (int it = 0; it < 60; it++) {
    for (int a = 0; a < 256; a++) {
      for (int b = 0; b < 256; b++) {
        for (int c = 0; c < 3; c++) {
          size_t i = (size_t)(a * 256 + b) * 3 + c;
          double p = F[a * 3 + c] + G[b * 3 + c];
          double o = obs[i];
          tgt[i] = ((o <= 0.5 && p < 0) || (o >= 254.5 && p > 255)) ? p : o;
        }
      }
    }
    for (int a = 0; a < 256; a++) {
      for (int c = 0; c < 3; c++) {
        double s = 0;
        for (int b = 0; b < 256; b++) s += tgt[(size_t)(a * 256 + b) * 3 + c] - G[b * 3 + c];
        F[a * 3 + c] = s / 256;
      }
    }
    for (int b = 0; b < 256; b++) {
      for (int c = 0; c < 3; c++) {
        double s = 0;
        for (int a = 0; a < 256; a++) s += tgt[(size_t)(a * 256 + b) * 3 + c] - F[a * 3 + c];
        G[b * 3 + c] = s / 256;
      }
    }
  }

  // how well it does on the watch's 64 colours
  long match = 0, worse = 0;
  double se = 0;
  for (int a = 0; a < 256; a++) {
    for (int b = 0; b < 256; b++) {
      bool same = true;
      for (int c = 0; c < 3; c++) {
        double o = obs[(size_t)(a * 256 + b) * 3 + c];
        double p = F[a * 3 + c] + G[b * 3 + c];
        p = p < 0 ? 0 : (p > 255 ? 255 : p);
        se += (p - o) * (p - o);
        int lo = (int)std::lround(o / 85), lp = (int)std::lround(p / 85);
        if (lo != lp) same = false;
        if (std::abs(lo - lp) > 1) worse++;
      }
      match += same;
    }
  }

  printf("// Generated by tools/gen_artifacts.cpp from the a7800 fork's composite video\n");
  printf("// model (a7800_composite.h: MiSTer's encoder and decoder, MIT). Do not edit.\n");
  printf("//\n");
  printf("// ARTIFACT_D[code] = (F - G) / 2, in 0-255 RGB: a 320-mode pair (a, b) shows as\n");
  printf("// the mean of a's and b's colours + D[a] - D[b].\n");
  printf("// Fit: rms %.2f of 255; the TV's own colour on the 64-colour screen for %.1f%%\n",
         std::sqrt(se / (256.0 * 256 * 3)), 100.0 * match / 65536);
  printf("// of the 65,536 pairs (the rest one step off in a channel, %ld further).\n", worse);
  printf("// Settings: smear 1, AGC on, comb off, artifact phase 1, warm, colour pin\n");
  printf("// offset 0.08 V.\n\n");
  printf("#ifndef ARTIFACT_TABLE_H\n#define ARTIFACT_TABLE_H\n\n#include <stdint.h>\n\n");
  printf("static const int8_t ARTIFACT_D[256][3] = {\n");
  for (int a = 0; a < 256; a++) {
    int v[3];
    for (int c = 0; c < 3; c++) {
      long d = std::lround((F[a * 3 + c] - G[a * 3 + c]) / 2);
      v[c] = (int)(d < -128 ? -128 : (d > 127 ? 127 : d));
    }
    printf("  {%d, %d, %d},%s", v[0], v[1], v[2], (a % 4 == 3) ? "\n" : "");
  }
  printf("};\n\n#endif\n");
  return 0;
}
