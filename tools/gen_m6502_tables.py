#!/usr/bin/env python3
"""Generate the watch core's opcode tables from the a7800 toolkit's m6502.py.

    python tools/gen_m6502_tables.py --toolkit ../a7800-toolkit \
        -o ../atari7800-40th/src/c/emu/m6502_tables.h

One table of opcodes for both projects: the mnemonic, addressing mode and base
cycle count of every opcode come from the toolkit's `OPCODES` and `CYCLES`,
which were cross-checked there against DiStella and the published figures.
The page-crossing penalty set is the toolkit's rule (`PAGE_CROSS_MODES` minus
`PAGE_CROSS_FREE`), applied to the opcodes that read.
"""
import argparse
import os
import sys

MODE_ENUM = ["imp", "acc", "imm", "zp", "zpx", "zpy", "izx", "izy",
             "abs", "abx", "aby", "ind", "rel"]


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--toolkit", required=True, help="path to the a7800-toolkit checkout")
    ap.add_argument("-o", "--output", required=True)
    args = ap.parse_args()

    sys.path.insert(0, os.path.join(args.toolkit, "tools"))
    import m6502  # noqa: E402  (the toolkit's module)

    mnemonics = sorted({mn for mn, _, _ in m6502.OPCODES.values()})
    # the toolkit spells SBC $EB as SBC; keep one enum value per mnemonic
    lines = []
    w = lines.append
    w("// Generated by a7800-pebble-tools/tools/gen_m6502_tables.py from the")
    w("// a7800 toolkit's tools/m6502.py. Do not edit by hand.")
    w("#ifndef M6502_TABLES_H")
    w("#define M6502_TABLES_H")
    w("")
    w("enum {")
    for m in MODE_ENUM:
        w("  AM_%s," % m.upper())
    w("};")
    w("")
    w("enum {")
    for mn in mnemonics:
        w("  OP_%s," % mn)
    w("};")
    w("")

    def table(name, values):
        w("static const uint8_t %s[256] = {" % name)
        for row in range(16):
            vals = values[row * 16:(row + 1) * 16]
            w("  " + ", ".join(vals) + ",  // %X0" % row)
        w("};")
        w("")

    table("M6502_MODE", ["AM_%s" % m6502.OPCODES[op][1].upper() for op in range(256)])
    table("M6502_OP", ["OP_%s" % m6502.OPCODES[op][0] for op in range(256)])
    table("M6502_CYCLES", ["%d" % m6502.CYCLES[op] for op in range(256)])

    pen = []
    for op in range(256):
        mn, md, _ = m6502.OPCODES[op]
        reads = md in m6502.PAGE_CROSS_MODES and mn not in m6502.PAGE_CROSS_FREE
        # the toolkit's free list covers the documented stores and RMWs and the
        # RMW illegals; the illegal stores pay the cycle unconditionally too
        if mn in ("SAX", "SHA", "SHX", "SHY", "TAS"):
            reads = False
        pen.append("1" if reads else "0")
    table("M6502_PAGE_PENALTY", pen)

    w("#endif")
    with open(args.output, "w") as f:
        f.write("\n".join(lines) + "\n")
    print("wrote %s (%d mnemonics)" % (args.output, len(mnemonics)))


if __name__ == "__main__":
    main()
